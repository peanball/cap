// loadFixture reads name out of testdata/ (populated by `go run ./test`,
// hashed into fixtures.sha256 and pinned by internal/testgenpcap's drift
// test) and returns its records with wall-clock-independent timestamps.
func loadFixture(t *testing.T, name string) []pcap.Record {
	t.Helper()
	raw, err := os.ReadFile(filepath.Join("testdata", name))
	if err != nil {
		t.Fatalf("read testdata/%s: %v (run `go run ./test`)", name, err)
	}
	recs, err := testgenpcap.ReadAll(raw)
	if err != nil {
		t.Fatalf("parse testdata/%s: %v", name, err)
	}
	return recs
}

// buildTLSCH is a minimal ClientHello carrying the given SNI, already
// wrapped in a TLS record. Kept as a thin alias of the shared builder so
// matchedStreamPcap and PlainStreamRejected stay short.
func buildTLSCH(sni string) []byte { return testgenpcap.TLSCH(sni) }

// eth is testgenpcap.EthIPv4 src/dst-in- Ethernet; the first two arguments
// (kept for call-site symmetry with the old builder) are the src/dst MAC.
func eth(srcMAC, dstMAC []byte, src, dst net.IP, sp, dp uint16, seq, ack uint32, flags uint8, payload []byte) []byte {
	return testgenpcap.Eth(srcMAC, dstMAC, 0x0800, testgenpcap.IPv4TCP(src, dst, sp, dp, seq, ack, flags, payload))
}

// TestSNIFragmentedCH verifies that a CH split across two TCP segments is
// reassembled and matched. The scenario lives in testdata/sni_fragmented.pcap
// (open it in Wireshark to see the split) and is regenerated by `go run ./test`.
func TestSNIFragmentedCH(t *testing.T) {
	records := loadFixture(t, "sni_fragmented.pcap")

	var outBuf bytes.Buffer
	wr := pcap.NewWriterRaw(&outBuf, pcap.LinkEthernet, 65535, false, pcap.FormatClassic)
	m, _ := match.NewSNI([]string{"peanball.net"})
	eng, _ := engine.New(engine.Config{Matcher: m}, wr)
	for _, r := range records {
		if err := eng.Process(pcap.LinkEthernet, r.Timestamp, r.Data); err != nil {
			t.Fatalf("Process: %v", err)
		}
	}
	eng.Close()

	rdr, _ := pcap.NewReader(bytes.NewReader(outBuf.Bytes()))
	kept := 0
	for {
		if _, err := rdr.Record(); err != nil {
			break
		}
		kept++
	}
	if kept != len(records) {
		t.Errorf("fragmented CH: kept %d of %d", kept, len(records))
	}
}

// TestSNIOnlyMatchedStreamKeptInOutput runs the engine against the
// two-stream pcap in testdata/sni_two_streams.pcap (one connection matches
// target.example.com, the other doesn't) and asserts only the wanted stream
// appears in the output.
func TestSNIOnlyMatchedStreamKeptInOutput(t *testing.T) {
	records := loadFixture(t, "sni_two_streams.pcap")

	var outBuf bytes.Buffer
	wr := pcap.NewWriterRaw(&outBuf, pcap.LinkEthernet, 65535, false, pcap.FormatClassic)
	m, err := match.NewSNI([]string{"target.example.com"})
	if err != nil {
		t.Fatalf("NewSNI: %v", err)
	}
	eng, err := engine.New(engine.Config{
		Matcher: m, IdleTimeout: time.Minute, MaxStreams: 100, WindowBytes: 64 << 10,
	}, wr)
	if err != nil {
		t.Fatalf("New: %v", err)
	}
	for _, r := range records {
		if err := eng.Process(pcap.LinkEthernet, r.Timestamp, r.Data); err != nil {
			t.Fatalf("Process: %v", err)
		}
	}
	eng.Close()

	rdr, err := pcap.NewReader(bytes.NewReader(outBuf.Bytes()))
	if err != nil {
		t.Fatalf("NewReader(out): %v", err)
	}
	var keptCount int
	// ethLen past the Ethernet header; IPv4 src/dst are the 4-byte words at
	// offsets 12 and 16 into the IP header (RFC 791).
	const ethLen = testgenpcap.EthHdrLen
	for {
		rec, err := rdr.Record()
		if err != nil {
			break
		}
		keptCount++
		if len(rec.Data) < ethLen+testgenpcap.IPv4HdrLen {
			t.Fatal("short record out")
		}
		srcIP := net.IP(rec.Data[ethLen+12 : ethLen+16]).String()
		if srcIP != "10.0.0.1" {
			t.Errorf("record with src %s (stream B?) leaked into output", srcIP)
		}
	}
	if keptCount == 0 {
		t.Fatal("no records in output; expected stream A to be kept")
	}
	t.Logf("kept %d records (all stream A)", keptCount)
}

// countingWriter records how many Write calls reached the sink, i.e. how
// many times output was actually pushed out.
type countingWriter struct {
	bytes.Buffer
	writes int
}

func (c *countingWriter) Write(p []byte) (int, error) {
	c.writes++
	return c.Buffer.Write(p)
}

// matchedStreamPcap is one connection to target.example.com: handshake, the
// ClientHello, then nData client data segments and, if closed, both FINs and
// the final ACK. Every packet is expected in the output. It returns the pcap
// bytes and the packet count.
func matchedStreamPcap(t *testing.T, nData int, closed bool) ([]byte, int) {
	t.Helper()
	srcMAC := []byte{0x00, 0x11, 0x22, 0x33, 0x44, 0x55}
	dstMAC := []byte{0x66, 0x77, 0x88, 0x99, 0xaa, 0xbb}
	cli, srv := net.ParseIP("10.0.0.1"), net.ParseIP("93.184.216.34")
	ch := buildTLSCH("target.example.com")

	var buf bytes.Buffer
	wr := pcap.NewWriterRaw(&buf, pcap.LinkEthernet, 65535, false, pcap.FormatClassic)
	t0 := time.Now()
	n := 0
	add := func(frame []byte) {
		ts := t0.Add(time.Duration(n) * time.Millisecond)
		rec := pcap.Record{Timestamp: ts, Data: frame}
		if err := wr.Record(rec); err != nil {
			t.Fatal(err)
		}
		n++
	}
	add(eth(srcMAC, dstMAC, cli, srv, 50001, 443, 1000, 0, 0x02, nil))
	add(eth(dstMAC, srcMAC, srv, cli, 443, 50001, 9000, 1001, 0x12, nil))
	add(eth(srcMAC, dstMAC, cli, srv, 50001, 443, 1001, 9001, 0x10, nil))
	add(eth(srcMAC, dstMAC, cli, srv, 50001, 443, 1001, 9001, 0x18, ch))
	seq := 1001 + uint32(len(ch))
	for i := 0; i < nData; i++ {
		add(eth(srcMAC, dstMAC, cli, srv, 50001, 443, seq, 9001, 0x18, []byte("data")))
		seq += 4
	}
	if closed {
		add(eth(srcMAC, dstMAC, cli, srv, 50001, 443, seq, 9001, 0x11, nil))   // client FIN
		add(eth(dstMAC, srcMAC, srv, cli, 443, 50001, 9001, seq+1, 0x11, nil)) // server FIN
		add(eth(srcMAC, dstMAC, cli, srv, 50001, 443, seq+1, 9002, 0x10, nil)) // final ACK
	}
	return buf.Bytes(), n
}

func countRecords(t *testing.T, pcapBytes []byte) int {
	t.Helper()
	rdr, err := pcap.NewReader(bytes.NewReader(pcapBytes))
	if err != nil {
		t.Fatalf("NewReader(out): %v", err)
	}
	n := 0
	for {
		if _, err := rdr.Record(); err != nil {
			return n
		}
		n++
	}
}

func runStream(t *testing.T, in io.Reader, o *Options, out io.Writer, sigs <-chan os.Signal, exit func(int)) {
	t.Helper()
	rdr, err := pcap.NewReader(in)
	if err != nil {
		t.Fatalf("NewReader: %v", err)
	}
	m, err := match.NewSNI([]string{"target.example.com"})
	if err != nil {
		t.Fatal(err)
	}
	if err := stream(o, m, nil, rdr, out, sigs, exit); err != nil {
		t.Fatalf("stream: %v", err)
	}
}

// TestNgAutoRoundtrip sends ng input through cap and checks the output is ng
// (auto mirrors the input container).
func TestNgAutoRoundtrip(t *testing.T) {
	records := loadFixture(t, "sni_two_streams.pcap")
	var in bytes.Buffer
	if err := func() error {
		w := pcap.NewWriterRaw(&in, pcap.LinkEthernet, 65535, false, pcap.FormatNg, pcap.WithFilterComment("test-filter"))
		if w.Err() != nil {
			return w.Err()
		}
		for _, r := range records {
			if err := w.Record(r); err != nil {
				return err
			}
		}
		return w.Flush()
	}(); err != nil {
		t.Fatal(err)
	}
	ngMagic := []byte{0x0a, 0x0d, 0x0d, 0x0a}
	if got := in.Bytes()[:4]; !bytes.Equal(got, ngMagic) {
		t.Fatalf("input prep: got magic %x, want pcapng %x", got, ngMagic)
	}

	var out bytes.Buffer
	runStream(t, bytes.NewReader(in.Bytes()), &Options{SNI: []string{"target.example.com"}, Ng: "auto"}, &out, nil, func(int) {})
	if got := out.Bytes()[:4]; !bytes.Equal(got, ngMagic) {
		t.Errorf("auto output magic: %x, want pcapng %x (auto mirrors ng input)", got, ngMagic)
	}
}

// TestPKTAPInputMatchesInner: the pktap_sni.pcap fixture is one TCP stream
// on Darwin's `-i any` wire; cap fed with --sni must match the inner TLS
// ClientHello, i.e. the PKTAP wrapper must not be the key.
func TestPKTAPInputMatchesInner(t *testing.T) {
	records := loadFixture(t, "pktap_sni.pcap")
	var in bytes.Buffer
	// Marshal with linktype = records[0].LinkType so the pcap header says PKTAP.
	w := pcap.NewWriterRaw(&in, records[0].LinkType, 65535, false, pcap.FormatClassic)
	for _, r := range records {
		if err := w.Record(r); err != nil {
			t.Fatal(err)
		}
	}

	var out bytes.Buffer
	runStream(t, bytes.NewReader(in.Bytes()), &Options{SNI: []string{"target.example.com"}}, &out, nil, func(int) {})
	got := countRecords(t, out.Bytes())
	if got == 0 {
		t.Error("no records in output; PKTAP wrapper hid the SNI match")
	}
}

// TestNgFlagMatrix runs the two-stream fixture through each --ng value and
// asserts the output container matches: classic magic for "false", pcapng
// magic (0a 0d 0d 0a) for "true". "auto" mirrors input — fixture is classic,
// so auto produces classic here.
func TestNgFlagMatrix(t *testing.T) {
	records := loadFixture(t, "sni_two_streams.pcap")
	var in bytes.Buffer
	w := pcap.NewWriterRaw(&in, pcap.LinkEthernet, 65535, false, pcap.FormatClassic)
	for _, r := range records {
		if err := w.Record(r); err != nil {
			t.Fatal(err)
		}
	}

	for _, ng := range []string{"auto", "true", "false"} {
		t.Run("ng="+ng, func(t *testing.T) {
			var out bytes.Buffer
			runStream(t, bytes.NewReader(in.Bytes()), &Options{SNI: []string{"target.example.com"}, Ng: ng}, &out, nil, func(int) {})
			got := out.Bytes()[:4]
			switch ng {
			case "true":
				want := []byte{0x0a, 0x0d, 0x0d, 0x0a}
				if !bytes.Equal(got, want) {
					t.Errorf("ng=true output magic: %x, want pcapng %x", got, want)
				}
			default:
				// classic pcap µs little-endian: d4 c3 b2 a1
				want := []byte{0xd4, 0xc3, 0xb2, 0xa1}
				if !bytes.Equal(got, want) {
					t.Errorf("ng=%s output magic: %x, want classic %x", ng, got, want)
				}
			}
		})
	}
}

// TestUnbufferedFlushesPerPacket: -U pushes output out packet by packet,
// the default batches it, and the bytes are identical either way.
func TestUnbufferedFlushesPerPacket(t *testing.T) {
	const nData = 20
	in, npkts := matchedStreamPcap(t, nData, false)

	run := func(unbuffered bool) *countingWriter {
		var out countingWriter
		runStream(t, bytes.NewReader(in), &Options{Unbuffered: unbuffered}, &out, nil, func(int) {})
		if got := countRecords(t, out.Bytes()); got != npkts {
			t.Fatalf("unbuffered=%v: %d records out, want %d", unbuffered, got, npkts)
		}
		return &out
	}
	buffered, unbuffered := run(false), run(true)

	if !bytes.Equal(buffered.Bytes(), unbuffered.Bytes()) {
		t.Error("output differs between buffered and unbuffered")
	}
	if unbuffered.writes < nData {
		t.Errorf("unbuffered made %d writes for %d data packets, want one per packet", unbuffered.writes, nData)
	}
	if buffered.writes >= nData/2 {
		t.Errorf("buffered made %d writes for %d data packets, want them batched", buffered.writes, nData)
	}
}

// signalAfter serves b, then on the next read raises os.Interrupt on sigs
// and blocks until the exit hook has run, as a signal arriving while the
// real program waits for input would.
type signalAfter struct {
	b      *bytes.Reader
	sigs   chan os.Signal
	exited chan struct{}
}

func (r *signalAfter) Read(p []byte) (int, error) {
	if r.b.Len() > 0 {
		return r.b.Read(p)
	}
	r.sigs <- os.Interrupt
	<-r.exited
	return 0, io.EOF
}

// TestSignalFlushesBufferedOutput: a signal must not strand matched packets
// in the output buffer, or `tcpdump | cap | tshark` loses them on Ctrl-C.
func TestSignalFlushesBufferedOutput(t *testing.T) {
	in, npkts := matchedStreamPcap(t, 5, false)
	r := &signalAfter{b: bytes.NewReader(in), sigs: make(chan os.Signal, 1), exited: make(chan struct{})}

	var out bytes.Buffer
	var atExit []byte
	var code int
	exit := func(c int) {
		code, atExit = c, bytes.Clone(out.Bytes())
		close(r.exited)
	}
	runStream(t, r, &Options{}, &out, r.sigs, exit)

	if code != 130 {
		t.Errorf("exit code = %d, want 130", code)
	}
	if got := countRecords(t, atExit); got != npkts {
		t.Errorf("%d records flushed by the time of exit, want %d", got, npkts)
	}
}

// whenDry serves b, then calls hook once the input runs dry, which is where
// a live pipe would block, before reporting EOF.
type whenDry struct {
	b    *bytes.Reader
	hook func()
}

func (r *whenDry) Read(p []byte) (int, error) {
	if r.b.Len() > 0 {
		return r.b.Read(p)
	}
	r.hook()
	return 0, io.EOF
}

// TestFlushWhenKeptStreamCloses: without -U, a connection that has closed
// (including its late packets) is already in the output when the input goes
// quiet, while one still open stays in the buffer.
func TestFlushWhenKeptStreamCloses(t *testing.T) {
	for _, tc := range []struct {
		name   string
		closed bool
	}{{"open", false}, {"closed", true}} {
		t.Run(tc.name, func(t *testing.T) {
			in, npkts := matchedStreamPcap(t, 5, tc.closed)
			var out bytes.Buffer
			var whenQuiet int
			r := &whenDry{b: bytes.NewReader(in)}
			r.hook = func() { whenQuiet = countRecords(t, out.Bytes()) }
			runStream(t, r, &Options{}, &out, nil, func(int) {})

			want := 0
			if tc.closed {
				want = npkts
			}
			if whenQuiet != want {
				t.Errorf("%d records in the output when the input went quiet, want %d", whenQuiet, want)
			}
		})
	}
}
